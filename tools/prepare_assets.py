"""Export PSP-sized artwork and embedded font masks. Requires Pillow.
The wallpaper is generated artwork; resizing here is build-time asset conversion.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont, ImageOps

root = Path(__file__).resolve().parents[1]
assets = root / "assets"
font_path = assets / "NotoSans.ttf"
wall = ImageOps.fit(Image.open(assets / "wallpaper-original.png").convert("RGB"),
                    (480, 272), method=Image.Resampling.LANCZOS)
wall.save(assets / "wallpaper.png")

def font(size):
    return ImageFont.truetype(str(font_path), size)

# A simple, reproducible brand mark: two opposing transfer arrows.
def mark(draw, x, y, scale=1):
    def p(points):
        return [(round(x+a*scale), round(y+b*scale)) for a,b in points]
    draw.polygon(p([(0,8),(31,8),(31,0),(45,14),(31,28),(31,20),(0,20)]),
                 fill="#65f6da")
    draw.polygon(p([(45,36),(14,36),(14,28),(0,42),(14,56),(14,48),(45,48)]),
                 fill="#f0f8ff")

icon = Image.new("RGB", (144*4,80*4), "#081c2b")
d = ImageDraw.Draw(icon)
d.rounded_rectangle((3*4,3*4,141*4,77*4), radius=13*4,
                    fill="#102c40", outline="#27516a", width=4)
mark(d, 15*4, 14*4, 0.85*4)
d.text((63*4,17*4), "Pocket", font=font(17*4), fill="#f3f9ff")
d.text((63*4,39*4), "Send", font=font(17*4), fill="#65f6da")
icon.resize((144,80), Image.Resampling.LANCZOS).save(assets/"ICON0.PNG")

pic = wall.copy()
d = ImageDraw.Draw(pic)
mark(d, 28, 74, 1.1)
d.text((95,63), "PocketSend", font=font(32), fill="#f3f9ff")
d.text((97,108), "Your files. No cables.", font=font(17), fill="#b3cddd")
d.text((29,215), "PSP  /  WIRELESS FILE TRANSFER", font=font(15), fill="#65f6da")
pic.save(assets/"PIC1.PNG")

def array(out, ctype, name, values, cols=24):
    out.write(f"const {ctype} {name}[{len(values)}] = {{\n")
    for i in range(0,len(values),cols):
        out.write(",".join(str(v) for v in values[i:i+cols])+",\n")
    out.write("};\n")

with (root/"src/assets.c").open("w") as out:
    out.write("/* Generated by tools/prepare_assets.py; see assets/FONT-LICENSE.txt. */\n#include <stdint.h>\n")
    array(out,"uint32_t","wallpaper_pixels",
          [r|(g<<8)|(b<<16)|0xff000000 for r,g,b in wall.getdata()])
    for index,size in enumerate((15,18,26)):
        f=font(size)
        masks=[]; advances=[]
        for code in range(32,127):
            tile=Image.new("L",(32,38))
            ImageDraw.Draw(tile).text((0,-3),chr(code),font=f,fill=255)
            masks.extend(tile.tobytes())
            advances.append(round(f.getlength(chr(code))))
        array(out,"unsigned char",f"font_{index}",masks)
        array(out,"unsigned char",f"advance_{index}",advances)
print("Exported 480x272 background, launcher artwork, and 15/18/26px font masks.")
